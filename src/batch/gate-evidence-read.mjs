/**
 * Gate and evidence path readers — leaf module (SP-432 / #83-D).
 * No imports from evidence, gate, reconcile, or postmortem.
 */

import fs from "node:fs";
import path from "node:path";

const TASKPLANE_CONFIG_PATH = ".pi/taskplane-config.json";

/**
 * @param {string} projectRoot
 * @param {string} batchId
 */
export function gateRecordPath(projectRoot, batchId) {
	return path.join(projectRoot, ".spine", "runtime", batchId, "gate.json");
}

/**
 * @param {string} projectRoot
 * @param {string} batchId
 * @returns {object|null}
 */
export function loadGateRecord(projectRoot, batchId) {
	const filePath = gateRecordPath(projectRoot, batchId);
	if (!fs.existsSync(filePath)) return null;

	try {
		return JSON.parse(fs.readFileSync(filePath, "utf-8"));
	} catch {
		return null;
	}
}

/**
 * @param {object} gate
 */
export function formatGateSummary(gate) {
	const status = String(gate.status ?? "unknown");
	const kind = String(gate.kind ?? "integrate");
	const evidenceCount = Array.isArray(gate.evidenceRefs) ? gate.evidenceRefs.length : 0;
	return `${kind} gate ${status} (${evidenceCount} evidence artifact(s))`;
}

/**
 * @param {string} projectRoot
 * @param {string} batchId
 */
export function evidenceDir(projectRoot, batchId) {
	return path.join(projectRoot, ".spine", "runtime", batchId, "evidence");
}

/**
 * @param {string} projectRoot
 * @param {string} batchId
 */
export function evidenceCompletePath(projectRoot, batchId) {
	return path.join(evidenceDir(projectRoot, batchId), ".complete");
}

/**
 * @param {string} projectRoot
 * @param {string} batchId
 */
export function isEvidenceBundleComplete(projectRoot, batchId) {
	return fs.existsSync(evidenceCompletePath(projectRoot, batchId));
}

/**
 * @param {object|null|undefined} batchState
 */
export function buildTaskScorecard(batchState) {
	const tasks = Array.isArray(batchState?.tasks) ? batchState.tasks : [];
	const lines = [
		"# Batch evidence summary",
		"",
		`| Field | Value |`,
		`|-------|-------|`,
		`| Batch ID | ${batchState?.batchId ?? batchState?.id ?? "—"} |`,
		`| Phase | ${batchState?.phase ?? "—"} |`,
		`| Base branch | ${batchState?.baseBranch ?? "—"} |`,
		`| Orch branch | ${batchState?.orchBranch ?? "—"} |`,
		`| Tasks (total) | ${batchState?.totalTasks ?? tasks.length} |`,
		`| Succeeded | ${batchState?.succeededTasks ?? "—"} |`,
		`| Failed | ${batchState?.failedTasks ?? "—"} |`,
		"",
		"## Task scorecard",
		"",
	];

	if (tasks.length === 0) {
		lines.push("_No task rows in batch state._");
	} else {
		lines.push("| Task | Status | Done file |");
		lines.push("|------|--------|-----------|");
		for (const task of tasks) {
			lines.push(
				`| ${task.taskId ?? "—"} | ${task.status ?? "—"} | ${task.doneFileFound ? "yes" : "no"} |`,
			);
		}
	}

	lines.push("", "_Generated by pi-spine integrate gate (TP-021)._");
	return `${lines.join("\n")}\n`;
}

/**
 * @param {string} projectRoot
 */
function readTaskplaneTestingCommands(projectRoot) {
	const configPath = path.join(projectRoot, TASKPLANE_CONFIG_PATH);
	if (!fs.existsSync(configPath)) return null;

	try {
		const parsed = JSON.parse(fs.readFileSync(configPath, "utf-8"));
		return parsed?.taskRunner?.testing?.commands ?? null;
	} catch {
		return null;
	}
}

/**
 * @param {ReturnType<typeof loadSpineConfig>["config"]} config
 * @param {string} projectRoot
 */
export function resolveTestingCommands(config, projectRoot) {
	const spineTesting = config?.testing ?? {};
	const taskplane = readTaskplaneTestingCommands(projectRoot) ?? {};

	return {
		test:
			(typeof spineTesting.test === "string" && spineTesting.test.trim()) ||
			(typeof taskplane.unit === "string" && taskplane.unit.trim()) ||
			(typeof taskplane.test === "string" && taskplane.test.trim()) ||
			"",
		build:
			(typeof spineTesting.build === "string" && spineTesting.build.trim()) ||
			(typeof taskplane.build === "string" && taskplane.build.trim()) ||
			"",
		testWithCoverage:
			(typeof spineTesting.testWithCoverage === "string" && spineTesting.testWithCoverage.trim()) ||
			(typeof taskplane.testWithCoverage === "string" && taskplane.testWithCoverage.trim()) ||
			"",
	};
}
